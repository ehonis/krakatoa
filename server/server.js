/* Served to anyone: the icons and manifest a browser asks for on the sign-in
   page, and the service worker, which never caches /api. */
const PUBLIC_FILES = new Set(['/favicon.ico', '/favicon-32.png', '/icon-180.png', '/icon-192.png', '/icon-512.png', '/manifest.webmanifest', '/sw.js'])

/* Bearer tokens machine callers may use: the API token from Settings, and the
   Totem bridge secret (the gateway already holds it). */
const bearerTokens = (e) => [e.apiToken.value, e.totem.secret.value, process.env.BRIDGE_SECRET].filter(Boolean)

/** A same-origin path to go to after sign-in, or '/'. Parsed, not pattern-matched. */
function safeNext(n) {
  if (typeof n !== 'string' || !n.startsWith('/') || n.includes('\\')) return '/'
  try {
    const u = new URL(n, 'http://krakatoa.invalid')
    if (u.origin !== 'http://krakatoa.invalid' || u.pathname.startsWith('/api/')) return '/'
    return u.pathname + u.search + u.hash
  } catch {
    return '/'
  }
}

/*
 * Who is asking, for the sign-in lockout. Forwarded-for headers are only
 * believed from a proxy we trust: KRAKATOA_TRUST_PROXY=1 always, =0 never,
 * unset only when the TCP peer is this machine (cloudflared, a local nginx).
 * Anyone else could put any address in them and never be locked out.
 */
function trustsProxy(req) {
  const v = String(process.env.KRAKATOA_TRUST_PROXY || '').toLowerCase()
  if (/^(1|true|on|yes)$/.test(v)) return true
  if (/^(0|false|off|no)$/.test(v)) return false
  return authMod.isLoopback(req.socket.remoteAddress)
}
function clientKey(req) {
  const peer = String(req.socket.remoteAddress || '')
  if (!trustsProxy(req)) return peer
  const fwd = req.headers['cf-connecting-ip'] || String(req.headers['x-forwarded-for'] || '').split(',')[0]
  return String(fwd || peer).trim() || peer
}

/** Null when this request may change settings; otherwise why not. */
function settingsWriteRefused(req) {
  if (eff().auth.mode === 'proxy') {
    return authMod.isLoopback(req.socket.remoteAddress) ? null : 'In proxy mode, settings can only be changed through the proxy (a connection from this machine).'
  }
  return req.via === 'session' ? null : 'Settings can only be changed from a signed-in browser, not with an API token.'
}

/*
 * Cross-site request forgery. A non-GET request that says where it came from
 * (Origin, or Sec-Fetch-Site) must come from here. A bearer-token client sends
 * neither and is unaffected; a browser always sends at least one.
 */
function crossSite(req) {
  if (req.method === 'GET' || req.method === 'HEAD' || req.method === 'OPTIONS') return false
  const site = String(req.headers['sec-fetch-site'] || '').toLowerCase()
  if (site && site !== 'same-origin' && site !== 'none') return true
  const origin = req.headers.origin
  if (origin === undefined) return false
  if (origin === 'null') return true
  let o
  try { o = new URL(origin) } catch { return true }
  const allowed = new Set([String(req.headers.host || '').toLowerCase()])
  const pub = eff().publicUrl.value
  if (pub) { try { allowed.add(new URL(pub).host.toLowerCase()) } catch { /* not a URL */ } }
  if (trustsProxy(req) && req.headers['x-forwarded-host']) allowed.add(String(req.headers['x-forwarded-host']).split(',')[0].trim().toLowerCase())
  return !allowed.has(o.host.toLowerCase())
}
const wantsJson = (req) => /json/.test(String(req.headers['content-type'] || '')) || /application\/json/.test(String(req.headers.accept || ''))

/** A form post or a JSON body, either way. */
async function readForm(req) {
  const type = String(req.headers['content-type'] || '')
  if (/application\/x-www-form-urlencoded/.test(type)) {
    const raw = (await readRaw(req, 16 * 1024)).toString('utf8')
    return Object.fromEntries(new URLSearchParams(raw))
  }
  return readBody(req, 16 * 1024)
}

const html = (res, status, body, headers = {}) => {
  res.writeHead(status, { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-store', 'x-frame-options': 'DENY', ...headers })
  res.end(body)
}
const redirect = (res, to, headers = {}) => { res.writeHead(303, { location: to, 'cache-control': 'no-store', ...headers }); res.end() }

/**
 * The sign-in pages and the /api/auth routes. Returns true when it answered.
 * These are reachable without a session, by design.
 */
async function authRoutes(req, res, url) {
  const p = url.pathname
  const e = eff()
  const proxy = e.auth.mode === 'proxy'
  const secure = authMod.isHttps(req, e.publicUrl.value)

  if (p === '/login' && req.method === 'GET') {
    if (proxy) return redirect(res, '/'), true
    if (!auth.hasOwner()) return html(res, 503, pages.notSetUpPage()), true
    if (auth.readSession(req)) return redirect(res, safeNext(url.searchParams.get('next'))), true
    return html(res, 200, pages.loginPage({ next: safeNext(url.searchParams.get('next')) })), true
  }

  if (p === '/setup' && req.method === 'GET') {
    if (proxy) return redirect(res, '/'), true
    if (auth.hasOwner()) return redirect(res, '/login'), true
    if (!auth.checkSetupToken(url.searchParams.get('token'))) return html(res, 403, pages.badSetupLinkPage()), true
    return html(res, 200, pages.setupPage({ token: url.searchParams.get('token') })), true
  }

  if (!p.startsWith('/api/auth/')) return false
  if (proxy) return send(res, 400, { error: 'Sign-in is handled by the proxy on this install (KRAKATOA_AUTH=proxy).' }), true

  if (p === '/api/auth/setup' && req.method === 'POST') {
    const f = await readForm(req)
    const fail = (status, message) => (wantsJson(req)
      ? send(res, status, { error: message })
      : auth.checkSetupToken(f.token)
        ? html(res, status, pages.setupPage({ token: f.token, username: f.username, message }))
        : html(res, 403, pages.badSetupLinkPage()))
    if (f.confirm !== undefined && f.confirm !== f.password) return fail(400, 'The two passwords do not match.'), true
    try {
      const owner = auth.createOwner({ token: f.token, username: f.username, password: f.password })
      console.log(`[krakatoa] owner account "${owner.username}" created; the setup link no longer works`)
      const cookie = auth.cookie(auth.issueSession(owner.username), { secure })
      if (wantsJson(req)) return send(res, 200, { ok: true, user: owner.username }, { 'set-cookie': cookie }), true
      return redirect(res, '/?settings=ai', { 'set-cookie': cookie }), true
    } catch (err) {
      return fail(auth.checkSetupToken(f.token) ? 400 : 403, err.message), true
    }
  }

  if (p === '/api/auth/login' && req.method === 'POST') {
    const key = clientKey(req)
    const f = await readForm(req)
    const next = safeNext(f.next)
    if (loginLimiter.blocked(key)) {
      const msg = 'Too many attempts. Wait fifteen minutes and try again.'
      return (wantsJson(req) ? send(res, 429, { error: msg }) : html(res, 429, pages.loginPage({ next, message: msg }))), true
    }
    const user = auth.login(f.username, f.password)
    if (!user) {
      loginLimiter.fail(key)
      const msg = 'That username and password do not match.'
      return (wantsJson(req) ? send(res, 401, { error: msg }) : html(res, 401, pages.loginPage({ next, message: msg }))), true
    }
    loginLimiter.reset(key)
    const session = auth.issueSession(user.username)
    // The iPhone app keeps the session in its keychain and sends it as a header,
    // so it gets the value itself and no cookie (server/auth.js).
    if (wantsJson(req) && authMod.isNativeClient(req)) return send(res, 200, { ok: true, user: user.username, session }), true
    const cookie = auth.cookie(session, { secure })
    return (wantsJson(req) ? send(res, 200, { ok: true, user: user.username }, { 'set-cookie': cookie }) : redirect(res, next, { 'set-cookie': cookie })), true
  }

  if (p === '/api/auth/logout' && req.method === 'POST') {
    // Ends the session for real, not just this browser's copy of the cookie:
    // the session version moves on, so a copied cookie stops working too.
    if (auth.readSession(req)) auth.revokeSessions()
    const cookie = auth.cookie('', { secure, clear: true })
    // Drop HTTP-cached responses too (receipt photos are cached privately).
    // The app clears its own storage before calling this; see lib/signout.js.
    res.setHeader('clear-site-data', '"cache"')
    return (wantsJson(req) ? send(res, 200, { ok: true }, { 'set-cookie': cookie }) : redirect(res, '/login', { 'set-cookie': cookie })), true
  }

  if (p === '/api/auth/password' && req.method === 'POST') {
    const me = auth.readSession(req)
    if (!me) return send(res, 401, { error: 'Sign in first.' }), true
    const f = await readBody(req, 16 * 1024)
    try {
      const user = auth.changePassword(f.current, f.next)
      // The signing key rotated, so every other device is signed out; this one
      // gets a fresh session and stays in (as a cookie, or for the app, in the reply).
      const session = auth.issueSession(user.username)
      if (authMod.isNativeClient(req)) return send(res, 200, { ok: true, session }), true
      return send(res, 200, { ok: true }, { 'set-cookie': auth.cookie(session, { secure }) }), true
    } catch (err) {
      return send(res, 400, { error: err.message }), true
    }
  }

  return send(res, 404, { error: `no route for ${p}` }), true
}

/**
 * Everything else needs a session, a bearer token, or proxy mode. Returns true
 * when it answered (with a 401, a redirect, or the not-set-up page).
 */
function gate(req, res, url) {
  const p = url.pathname
  const e = eff()
  if (e.auth.mode === 'proxy') { req.user = null; req.via = 'proxy'; return false }
  if (PUBLIC_FILES.has(p)) return false
  const user = auth.readSession(req)
  if (user) { req.user = user; req.via = 'session'; return false }
  const isApi = p.startsWith('/api/') || p === '/mcp'
  if (isApi && auth.bearerOk(req, bearerTokens(e))) { req.user = null; req.via = 'bearer'; return false }
  if (!auth.hasOwner()) {
    if (isApi) return send(res, 401, { error: 'This install is not set up yet. Open the setup link in the server log.', setup: true }), true
    return html(res, 503, pages.notSetUpPage()), true
  }
  if (isApi) return send(res, 401, { error: 'Sign in first.', signIn: '/login' }, { 'www-authenticate': 'Bearer' }), true
  return redirect(res, `/login?next=${encodeURIComponent(url.pathname + url.search)}`), true
}

/* ------------------------------------------------------------------- serve */

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host || 'localhost'}`)
  try {
    if (crossSite(req)) return send(res, 403, { error: 'Cross-site request refused.' })
    if (await authRoutes(req, res, url)) return
    if (gate(req, res, url)) return
    if (url.pathname.startsWith('/api/') || url.pathname === '/mcp') return await api(req, res, url)
    return await serveStatic(req, res, url.pathname)
  } catch (e) {
    if (e.status) return send(res, e.status, { error: e.message })
    console.error('[krakatoa]', req.method, url.pathname, e)
    send(res, 500, { error: String(e.message || e) })
  }
})

server.listen(PORT, BIND, () => {
  const port = server.address().port
  console.log(`[krakatoa] listening on ${BIND}:${port}`)
  console.log(`[krakatoa] state  ${STATE_FILE}`)
  console.log(`[krakatoa] dist   ${DIST_DIR}`)
  if (!fs.existsSync(path.join(DIST_DIR, 'index.html'))) console.log('[krakatoa] the app is not built yet: run `npm run build` (or `npm start`, which builds first)')
  const e = eff()
  if (e.auth.mode === 'proxy') {
    console.log('[krakatoa] sign-in: left to the proxy in front of this server (KRAKATOA_AUTH=proxy)')
    if (!authMod.isLoopback(BIND) && BIND !== 'localhost') {
      console.warn([
        '',
        '[krakatoa] ************************************************************************',
        `[krakatoa] WARNING: proxy mode, but listening on ${BIND}, not only on loopback.`,
        '[krakatoa] Anyone who can reach this port directly can read and write the log',
        '[krakatoa] with no sign-in. Settings can still only be changed from this machine.',
        '[krakatoa] Bind to 127.0.0.1 (KRAKATOA_BIND) or firewall the port to the proxy.',
        '[krakatoa] ************************************************************************',
        '',
      ].join('\n'))
    }
  } else if (!auth.hasOwner()) {
    const base = (e.publicUrl.value || `http://localhost:${port}`).replace(/\/+$/, '')
    console.log(`\n[krakatoa] No owner account yet. Open this link to set up Krakatoa (it works once):\n\n    ${base}/setup?token=${auth.issueSetupToken()}\n`)
  }
  // A run the last process was in the middle of is run again, not lost.
  runner.recover().then(n => { if (n) console.log(`[krakatoa] ask: resuming ${n} unfinished`) }).catch(() => {})
})

