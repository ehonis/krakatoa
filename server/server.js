/** Serve the built app. Unknown paths fall through to index.html (SPA routing). */
async function serveStatic(req, res, urlPath) {
  const clean = path.normalize(decodeURIComponent(urlPath)).replace(/^(\.\.[/\\])+/, '')
  let file = path.join(DIST_DIR, clean)
  if (!file.startsWith(DIST_DIR)) return send(res, 403, 'no')

  try {
    const stat = await fsp.stat(file)
    if (stat.isDirectory()) file = path.join(file, 'index.html')
  } catch {
    file = path.join(DIST_DIR, 'index.html')
  }

  try {
    const body = await fsp.readFile(file)
    const ext = path.extname(file)
    // The wasm and the hashed assets are immutable; index.html never is, or a
    // phone keeps yesterday's bundle forever. Same trap Bushido documents.
    const immutable = /\.[0-9a-f]{8,}\./.test(file) || ext === '.wasm'
    res.writeHead(200, {
      'content-type': MIME[ext] || 'application/octet-stream',
      'cache-control': immutable ? 'public, max-age=31536000, immutable' : 'no-cache',
    })
    res.end(body)
  } catch {
    send(res, 404, 'not found')
  }
}

/* ------------------------------------------------------------------ routes */

async function api(req, res, url) {
  const p = url.pathname
  const q = url.searchParams

  if (p === '/api/me') {
    const e = eff()
    return send(res, 200, {
      user: req.user?.username || null,
      authMode: e.auth.mode,
      features: {
        ai: aiReady(),
        whoop: !!totemCfg(),
        totem: !!totemCfg(),
        usda: !!e.usda.value,
        nutritionix: !!nutritionix.credsFrom(nixConfig()),
      },
    })
  }

  if (p === '/api/settings' && req.method === 'GET') {
    return send(res, 200, { ...settingsMod.publicView(eff()), owner: auth.owner() })
  }

  /*
   * Changing settings (and the Test buttons, which reach out from the server)
   * needs a signed-in browser session, never an API token: a token handed to an
   * MCP client must not be able to rewrite keys or the bridge URL. In proxy mode
   * there are no sessions, so it needs the request to come from this machine,
   * which is where cloudflared and local reverse proxies connect from.
   */
  if (p.startsWith('/api/settings') && (req.method !== 'GET' || p === '/api/settings/test')) {
    const why = settingsWriteRefused(req)
    if (why) return send(res, 403, { error: why })
  }

  if (p === '/api/settings' && req.method === 'PUT') {
    let patch
    const body = await readBody(req, 64 * 1024)
    try { patch = settingsMod.guardTotemUrl(settingsMod.cleanPatch(body), eff()) } catch (e) { return send(res, 400, { error: e.message }) }
    settings.save(patch)
    return send(res, 200, { ...settingsMod.publicView(eff()), owner: auth.owner() })
  }

  if (p === '/api/settings/ai/status' && req.method === 'GET') {
    return send(res, 200, await settingsMod.aiStatus(eff()))
  }

  if (p === '/api/settings/test' && req.method === 'POST') {
    const body = await readBody(req, 16 * 1024)
    return send(res, 200, await testIntegration(String(body?.what || '')))
  }

  if (p === '/api/settings/token' && req.method === 'POST') {
    if (eff().apiToken.from === 'env') return send(res, 409, { error: 'The API token is set by KRAKATOA_API_TOKEN in the environment.' })
    const token = crypto.randomBytes(32).toString('base64url')
    settings.save({ apiToken: token })
    return send(res, 200, { token })
  }

  if (p === '/api/health') {
    const state = await readState()
    return send(res, 200, {
      ok: true,
      app: 'krakatoa',
      entries: Object.keys(state.entries).length,
      cachedFoods: Object.keys(foods()).length,
      usdaKey: usdaKey() === 'DEMO_KEY' ? 'DEMO_KEY (rate limited)' : 'configured',
      restaurants: nutritionix.credsFrom(nixConfig()) ? 'configured' : 'no Nutritionix key — see Settings',
      paths: { state: STATE_FILE, foods: FOODS_FILE, dist: DIST_DIR },
    })
  }

  if (p === '/api/state' && req.method === 'GET') {
    const doc = await readState()
    return send(res, 200, { version: doc.version, updatedAt: doc.updatedAt, state: doc })
  }

  if (p === '/api/state' && req.method === 'PUT') {
    const body = await readBody(req)
    const merged = await withState(doc => commit(doc, body?.state?.entries || body?.entries))
    return send(res, 200, { version: merged.version, updatedAt: merged.updatedAt, state: merged })
  }

  if (p === '/api/entry' && req.method === 'POST') {
    const body = await readBody(req)
    const entry = body?.entry
    if (!entry?.id) return send(res, 400, { error: 'an entry needs an id' })
    const merged = await withState(doc => commit(doc, { [entry.id]: entry }))
    return send(res, 200, { version: merged.version, updatedAt: merged.updatedAt, state: merged })
  }

  /*
   * A photo of the back of the package -> the numbers on it, to put in the form.
   * Nothing is stored and nothing is logged: the photo lives in a temp directory
   * for the length of one read, and what comes back is his to check and save.
   */
  if (p === '/api/label' && req.method === 'POST') {
    const type = String(req.headers['content-type'] || '').split(';')[0].trim()
    if (!['image/jpeg', 'image/png', 'image/webp'].includes(type)) {
      return send(res, 415, { error: 'Send the photo as a JPEG or PNG.' })
    }
    if (!aiReady()) return send(res, 503, { error: AI_NOT_SET_UP, setup: 'ai' })
    // Two at once is plenty for one person; more is a stuck button being tapped.
    if (labelsReading >= 2) return send(res, 429, { error: 'Still reading the last photo — give it a moment.' })
    let image
    try { image = await readRaw(req) } catch (e) { return send(res, 413, { error: e.message }) }
    if (image.length < 1000) return send(res, 400, { error: 'That photo came through empty — try again.' })
    labelsReading++
    try {
      const c = aiCfg()
      const out = await label.readLabel({ bin: c.bin, model: c.labelModel, timeoutMs: LABEL_TIMEOUT_MS, image, type, env: c.env })
      console.log(`[krakatoa] label read in ${out.ms} ms by ${out.model}${out.label.isLabel ? '' : ' (not a label)'}`)
      return send(res, 200, out)
    } catch (e) {
      console.error('[krakatoa] label read failed:', e.message)
      return send(res, 502, { error: String(e.message || e) })
    } finally {
      labelsReading--
    }
  }

  /*
   * Ask AI, in the background. POST starts (or continues) a THREAD and returns at
   * once with it; the server does the work; the phone reads the thread when it
   * is open. See server/aithreads.js for why — backing out of the app used to
   * kill a fifty-second run and lose the answer.
   */
  if (p === '/api/ask' && req.method === 'POST') {
    if (!aiReady()) return send(res, 503, { error: AI_NOT_SET_UP, setup: 'ai' })
    let body
    try { body = await readBody(req, 12 * 1024 * 1024) } catch (e) { return send(res, e.status === 415 ? 415 : 413, { error: e.status === 415 ? e.message : 'That photo is too large.' }) }
    const text = String(body?.text || '').slice(0, 2000)
    const message = String(body?.message || '').slice(0, 1000)
    const b64 = String(body?.image || '').replace(/^data:image\/\w+;base64,/, '')
    const image = b64 ? Buffer.from(b64, 'base64') : null
    if (image && image.length < 1000) return send(res, 400, { error: 'That photo came through empty — try again.' })
    const at = new Date().toISOString()

    let thread
    if (body?.threadId) {
      thread = await threads.read(String(body.threadId))
      if (!thread || thread.deleted) return send(res, 404, { error: 'That conversation is gone.' })
      if (thread.status === 'working') return send(res, 409, { error: 'Still working on the last one — give it a moment.' })
      if (!message.trim()) return send(res, 400, { error: 'Say what to change.' })
      thread.turns.push({ role: 'you', at, text: message, previous: body.previous || null })
    } else {
      if (!text.trim() && !image) return send(res, 400, { error: 'Send a photo or say what you had.' })
      thread = { id: aiThreads.newId(), createdAt: at, title: null, turns: [], draft: null }
      const photo = image ? await threads.savePhoto(thread.id, image) : null
      thread.turns.push({ role: 'you', at, text, photo })
    }
    thread.status = 'working'
    thread.error = null
    await threads.write(thread)
    runner.enqueue(thread.id)
    return send(res, 202, { thread })
  }

  if (p === '/api/ask/threads' && req.method === 'GET') {
    const all = await threads.list()
    return send(res, 200, { threads: all.slice(0, 100).map(aiThreads.summaryOf), busy: runner.busy })
  }

  const threadRoute = p.match(/^\/api\/ask\/threads\/([a-z0-9-]+)$/i)
  if (threadRoute) {
    const id = threadRoute[1]
    if (req.method === 'GET') {
      const t = await threads.read(id)
      return t && !t.deleted ? send(res, 200, { thread: t }) : send(res, 404, { error: 'That conversation is gone.' })
    }
    if (req.method === 'DELETE') {
      return send(res, (await threads.remove(id)) ? 200 : 404, { ok: true })
    }
    if (req.method === 'POST') {
      // Small updates from the phone: his review draft, "seen", "logged", a
      // retry of a run that failed.
      const body = await readBody(req, 2 * 1024 * 1024)
      const t = await threads.read(id)
      if (!t || t.deleted) return send(res, 404, { error: 'That conversation is gone.' })
      if (body.draft !== undefined) t.draft = body.draft
      if (body.seen) t.seenAt = new Date().toISOString()
      if (body.logged) t.loggedAt = new Date().toISOString()
      if (typeof body.title === 'string') t.title = body.title.slice(0, 80) || null
      if (body.retry && t.status === 'error') { t.status = 'working'; t.error = null }
      await threads.write(t)
      if (t.status === 'working') runner.enqueue(t.id)
      return send(res, 200, { thread: t })
    }
  }

  const photoRoute = p.match(/^\/api\/ask\/photo\/([a-z0-9.-]+\.jpg)$/i)
  if (photoRoute) {
    try {
      const buf = await fsp.readFile(threads.photoPath(photoRoute[1]))
      return res.writeHead(200, { 'content-type': 'image/jpeg', 'cache-control': 'private, max-age=31536000, immutable' }).end(buf)
    } catch {
      return send(res, 404, { error: 'no such photo' })
    }
  }

  /*
   * A food he built from its label, remembered under its barcode — so the scan
   * that missed today finds it tomorrow, from the same cache every other scan
   * answers from. Without a barcode there is nothing to key it by, and the
   * client's star is what keeps it.
   */
  if (p === '/api/food' && req.method === 'POST') {
    const body = await readBody(req)
    const food = body?.food
    const gtin = nutrition.normalizeGtin(food?.gtin)
    if (!gtin) return send(res, 400, { error: 'a food needs a valid barcode to be remembered by one' })
    const portions = Array.isArray(food.portions) ? food.portions.filter(pt => pt && Number.isFinite(Number(pt.kcal))) : []
    if (!String(food.name || '').trim() || !portions.length) return send(res, 400, { error: 'a food needs a name and at least one portion with calories' })
    const saved = {
      gtin,
      name: String(food.name).trim().slice(0, 120),
      brand: food.brand ? String(food.brand).trim().slice(0, 80) : null,
      image: null,
      source: 'label',
      portions: portions.slice(0, 6),
    }
    await cacheFood(saved)
    return send(res, 200, { food: saved })
  }

  /* MCP for Totem's gateway (and anything else that speaks it). */
  if (p === '/mcp') {
    if (req.method !== 'POST') return send(res, 405, { error: 'POST JSON-RPC to /mcp' }, { allow: 'POST' })
    let body
    try { body = await readBody(req, 4 * 1024 * 1024) } catch (e) { return send(res, e.status === 415 ? 415 : 400, { jsonrpc: '2.0', id: null, error: { code: -32700, message: e.status === 415 ? e.message : 'parse error' } }) }
    if (Array.isArray(body)) {
      const out = (await Promise.all(body.map(m => mcp.handle(m)))).filter(Boolean)
      return out.length ? send(res, 200, out) : res.writeHead(202).end()
    }
    const out = await mcp.handle(body)
    return out ? send(res, 200, out) : res.writeHead(202).end()
  }

  if (p === '/api/lookup') {
    const code = q.get('code')
    const gtin = nutrition.normalizeGtin(code)
    if (!gtin) {
      // A bad check digit is a DIFFERENT answer from "we looked and it is not
      // there", and the screen says different things about them.
      return send(res, 200, { food: null, reason: 'not-a-barcode', code })
    }
    const cached = foods()[gtin]
    if (cached && q.get('fresh') !== '1') {
      return send(res, 200, { food: cached, reason: 'cache' })
    }
    const result = await lookup.lookupBarcode(gtin, { usdaKey: usdaKey() })
    if (result.food) await cacheFood(result.food)
    // Every source erroring is an OUTAGE, not a miss. The screen offers a retry
    // for one and manual entry for the other.
    const allFailed = result.tried.length > 0 && result.tried.every(t => t.error)
    return send(res, 200, {
      food: result.food,
      reason: result.food ? 'looked-up' : allFailed ? 'sources-down' : 'not-found',
      tried: result.tried,
    })
  }

  if (p === '/api/search') {
    const result = await lookup.searchFoods(q.get('q'), { usdaKey: usdaKey(), limit: 25 })
    // The rows he is about to look at, pulled while he is still reading them.
    // Only the top of the list: fetching twenty-five photos to show six is how a
    // slow CDN becomes a slow app.
    for (const food of result.foods.slice(0, 8)) {
      if (food.gtin && food.image) primeImage(food.gtin, food.image)
    }
    return send(res, 200, result)
  }

  /*
   * A product photo, proxied and kept. Three reasons it is not just an <img> at
   * OFF's CDN. It works in a supermarket with one bar of signal, because the
   * second time it is a file on this disk. It is same-origin, so the service
   * worker caches it like everything else. And his shopping does not become a
   * request log on somebody else's CDN.
   *
   * `u` is the URL the client already has; it is checked against a HOST
   * ALLOWLIST before anything is fetched, because a proxy that will fetch
   * whatever it is told to is an open relay with a friendly name. Once a gtin
   * is on disk `u` is ignored entirely.
   */
  if (p === '/api/image') {
    const gtin = nutrition.normalizeGtin(q.get('gtin'))
    if (!gtin) return send(res, 400, { error: 'not a barcode' })
    /*
     * Prefer what we already know about this gtin over what the caller claims,
     * and if we know nothing, ASK. That last step is what backfills: every food
     * logged before this app had photos is a real barcode with no image URL
     * anywhere, and re-reading the product once is the difference between those
     * entries getting a picture and staying letter tiles forever.
     */
    let url = foods()[gtin]?.image || q.get('u')
    if (!url || !nutrition.isAllowedImage(url)) {
      const fresh = await lookup.lookupBarcode(gtin, { usdaKey: usdaKey() }).catch(() => null)
      if (fresh?.food) {
        await cacheFood(fresh.food)
        url = fresh.food.image
      }
    }

    try {
      const buf = await fetchImage(gtin, url)
      if (!buf) return send(res, 404, { error: 'no image' })
      return res.writeHead(200, {
        'content-type': 'image/jpeg',
        // A product photo for a given barcode does not change in any way worth
        // a revalidation round trip on a phone.
        'cache-control': 'public, max-age=31536000, immutable',
      }).end(buf)
    } catch (e) {
      // An image that will not load must never be an error on screen — the row
      // falls back to its letter tile and the day still adds up.
      return send(res, 404, { error: String(e.message || e) })
    }
  }

  if (p === '/api/basics') {
    try {
      const body = await fsp.readFile(BASICS_FILE, 'utf8')
      return res.writeHead(200, {
        'content-type': 'application/json',
        // Content, not state: it only changes when the build script re-runs, and
        // the client keeps its own copy anyway.
        'cache-control': 'public, max-age=3600',
      }).end(body)
    } catch {
      // An absent catalog is a missing build step, not a broken app: search and
      // scanning are unaffected and the basics list simply renders empty.
      return send(res, 200, { categories: [], foods: [], error: 'basics.json has not been built' })
    }
  }

  /*
   * Chain restaurant menus. A separate route from /api/search rather than a
   * third source inside it, because this one costs a metered API call and the
   * others do not — folding it in would spend quota on every keystroke-debounced
   * grocery search. See server/nutritionix.js.
   */
  if (p === '/api/restaurant') {
    try {
      const out = await nutritionix.search(q.get('q'), nixConfig())
      return send(res, 200, out)
    } catch (e) {
      return send(res, 200, { foods: [], configured: true, error: String(e.message || e) })
    }
  }

  if (p === '/api/restaurant/item') {
    const gid = `nix:${String(q.get('id') || '').trim()}`
    const cached = foods()[gid]
    if (cached) return send(res, 200, { food: cached, reason: 'cache' })
    try {
      const food = await nutritionix.item(q.get('id'), nixConfig())
      if (!food) return send(res, 404, { error: 'no such item' })
      // Cached under its own key so a menu item he eats weekly costs one call
      // ever, not one a week.
      foods()[gid] = { ...food, fetchedAt: new Date().toISOString() }
      await fsp.mkdir(DATA_DIR, { recursive: true }).catch(() => {})
      await fsp.writeFile(FOODS_FILE, JSON.stringify(foodCache, null, 2)).catch(() => {})
      return send(res, 200, { food, reason: 'looked-up' })
    } catch (e) {
      return send(res, 502, { error: String(e.message || e) })
    }
  }

  if (p === '/api/whoop' && req.method === 'GET') {
    // Serves the cache and kicks off a refresh it does not wait for. WHOOP being
    // down must never make a screen slow, let alone fail.
    return send(res, 200, whoopStore.get())
  }

  if (p === '/api/whoop/pull' && req.method === 'POST') {
    return send(res, 200, await whoopStore.refresh())
  }

  if (p === '/api/restaurants') {
    // The built menus plus the ones Ask AI has learned from a chain's own page.
    const doc = await allRestaurants()
    const built = fs.existsSync(RESTAURANTS_FILE)
    return send(res, 200, { ...doc, built })
  }


  if (p === '/api/recent') {
    const state = await readState()
    return send(res, 200, { foods: digest.recentFoods(state, { limit: Number(q.get('limit') || 40) }) })
  }

  if (p === '/api/day') {
    const state = await readState()
    const date = q.get('date') || digest.isoDate(new Date())
    const day = digest.dayDigest(state, date)
    const balance = whoop.balanceFor(whoopStore.read(), date, day.total.kcal,
      { today: digest.isoDate(new Date()) })
    return send(res, 200, { ...day, balance })
  }

  if (p === '/api/digest') {
    const state = await readState()
    return send(res, 200, digest.digest(state, {
      today: q.get('today') || digest.isoDate(new Date()),
      days: Math.min(90, Math.max(1, Number(q.get('days') || 14))),
      whoop: whoopStore.read(),
    }))
  }

  if (p === '/api/export') {
    const doc = await readState()
    return send(res, 200, doc, {
      'content-disposition': `attachment; filename="krakatoa-${digest.isoDate(new Date())}.json"`,
    })
  }

  if (p === '/api/import' && req.method === 'POST') {
    const body = await readBody(req)
    if (!body?.entries) return send(res, 400, { error: 'an export has an entries object' })
    const merged = await withState(async () => {
      if (fs.existsSync(STATE_FILE)) await backup()
      const doc = { version: 1, updatedAt: new Date().toISOString(), entries: body.entries }
      await writeState(doc)
      return doc
    })
    return send(res, 200, { ok: true, entries: Object.keys(merged.entries).length })
  }

  return send(res, 404, { error: `no route for ${p}` })
}

