/* The menus and basics, parsed once and re-read only when the build scripts
   rewrite them. They are the bulk of the AI's food table. */
const contentCache = {}
async function contentJson(file) {
  try {
    const { mtimeMs } = await fsp.stat(file)
    const hit = contentCache[file]
    if (hit && hit.mtimeMs === mtimeMs) return hit.doc
    const doc = JSON.parse(await fsp.readFile(file, 'utf8'))
    contentCache[file] = { mtimeMs, doc }
    return doc
  } catch {
    return null
  }
}
