/* The chain menus: the built ones in content/, plus any Ask AI has learned. */
async function allRestaurants() {
  const built = (await contentJson(RESTAURANTS_FILE)) || { chains: [] }
  const extra = (await learned.load()).chains || []
  const have = new Set(built.chains.map(c => c.name.toLowerCase()))
  return { ...built, chains: [...built.chains, ...extra.filter(c => !have.has(c.name.toLowerCase()) && c.items.length)] }
}

/*
 * The rest of a chain's menu, once a receipt has shown Krakatoa a nutrition page
 * it could verify items on. Runs after the thread's answer has gone back, so
 * he never waits for it, and says what it added in the thread when it is done.
 */
const learning = new Set()
async function learnRestOfMenu(threadId, group) {
  if (learning.has(group.chain) || (group.text || '').length < 1500) return
  const have = ((await learned.load()).chains || []).find(c => c.name.toLowerCase() === group.chain.toLowerCase())
  if (have && have.items.length >= 40) return // already learned properly
  learning.add(group.chain)
  try {
    const c = aiCfg()
    const out = await ai.learnMenu({ bin: c.bin, model: c.askModel, chain: group.chain, text: group.text, env: c.env })
    const fresh = out.items.length ? await learned.add({ chain: group.chain, url: group.url, items: out.items, docDate: group.docDate }) : 0
    const t = await threads.read(threadId)
    if (t && !t.deleted) {
      t.turns.push({
        role: 'system',
        at: new Date().toISOString(),
        text: fresh
          ? `Added ${fresh} more ${group.chain} items to Krakatoa from their nutrition page — they are under Restaurant menus now.`
          : `Looked for the rest of ${group.chain}'s menu, but nothing more could be checked against their page.`,
      })
      await threads.write(t)
    }
    console.log(`[krakatoa] learned ${fresh} ${group.chain} items (${out.items.length} of ${out.offered} verified)`)
  } catch (e) {
    console.error(`[krakatoa] learning ${group.chain} failed:`, e.message)
  } finally {
    learning.delete(group.chain)
  }
}

async function runAsk(thread, turn) {
  const index = ai.buildIndex({
    state: await readState(),
    restaurants: await allRestaurants(),
    basics: await contentJson(BASICS_FILE),
  })
  const first = thread.turns.find(x => x.role === 'you')
  const photo = first?.photo ? await fsp.readFile(threads.photoPath(first.photo)).catch(() => null) : null
  const revising = turn !== first
  const c = aiCfg()
  const answer = await ai.askMeal({
    bin: c.bin, model: c.askModel, effort: c.askEffort, env: c.env, index,
    text: first?.text || '',
    image: photo,
    previous: revising ? turn.previous : null,
    message: revising ? turn.text : '',
  })
  // What it verified on a chain's own page is kept, and the rest of that page
  // is read in the background. The page text itself never goes in the thread.
  const groups = answer._learn || []
  delete answer._learn
  answer.learned = []
  for (const g of groups) {
    const fresh = await learned.add({ chain: g.chain, url: g.url, items: g.items, docDate: g.docDate })
    answer.learned.push({ chain: g.chain, items: g.items.length, fresh, url: g.url, docDate: g.docDate })
    learnRestOfMenu(thread.id, g)
  }
  return answer
}
const runner = aiThreads.makeRunner({ store: threads, run: runAsk })

/* A barcode to a food: the cache, then the databases. Shared by /api/lookup and the MCP. */
async function lookupCode(code) {
  const gtin = nutrition.normalizeGtin(code)
  if (!gtin) return { food: null, reason: 'not-a-barcode', code }
  const cached = foods()[gtin]
  if (cached) return { food: cached, reason: 'cache' }
  const result = await lookup.lookupBarcode(gtin, { usdaKey: usdaKey() })
  if (result.food) await cacheFood(result.food)
  const allFailed = result.tried.length > 0 && result.tried.every(t => t.error)
  return { food: result.food, reason: result.food ? 'looked-up' : allFailed ? 'sources-down' : 'not-found', tried: result.tried }
}

/*
 * Ask AI from the MCP: the same thread the app would make (so it shows up in
 * the app's list), waited on here because a tool call wants its answer.
 */
async function askAndWait(text, timeoutMs = 200000) {
  if (!aiReady()) throw new Error(AI_NOT_SET_UP)
  const at = new Date().toISOString()
  const thread = { id: aiThreads.newId(), createdAt: at, title: null, turns: [{ role: 'you', at, text, via: 'mcp' }], draft: null, status: 'working', error: null }
  await threads.write(thread)
  runner.enqueue(thread.id)
  const until = Date.now() + timeoutMs
  for (;;) {
    await new Promise(r => setTimeout(r, 1500))
    const t = await threads.read(thread.id)
    if (!t || t.status !== 'working' || Date.now() > until) return t || thread
  }
}

