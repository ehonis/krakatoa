/*
 * `node:https` rather than `fetch`, for one measured reason: OFF's image CDN is
 * in France and takes 10–15 seconds to complete a TLS connect from this box.
 * Undici — what global `fetch` is — has a hard-coded 10 second CONNECT timeout
 * that is not configurable without passing a dispatcher, so every image failed
 * with a bare "fetch failed" while curl fetched the same URL happily in 10.1s.
 * The built-in module takes the timeout as an argument and costs no dependency.
 */
const https = require('https')

function downloadImage(url, timeoutMs = 30000) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, { timeout: timeoutMs }, (res) => {
      if (res.statusCode !== 200) {
        res.resume()
        reject(new Error(`upstream ${res.statusCode}`))
        return
      }
      const chunks = []
      let size = 0
      res.on('data', (c) => {
        size += c.length
        // A front-of-pack thumbnail is ~10 KB. Anything past a megabyte is not
        // the thing we asked for and is not worth keeping.
        if (size > 1024 * 1024) { req.destroy(); reject(new Error('image too large')); return }
        chunks.push(c)
      })
      res.on('end', () => resolve(Buffer.concat(chunks)))
      res.on('error', reject)
    })
    req.on('timeout', () => { req.destroy(); reject(new Error('image timed out')) })
    req.on('error', reject)
  })
}

const imagePath = (gtin) => path.join(IMAGE_DIR, `${gtin}.jpg`)

/*
 * One in-flight download per gtin. A search returns twenty-five rows and the
 * page asks for twenty-five images at once; without this, a second render while
 * the first is still connecting starts the whole slow fetch again.
 */
const inFlight = new Map()

async function fetchImage(gtin, url) {
  if (!gtin || !nutrition.isAllowedImage(url)) return null
  const file = imagePath(gtin)
  try {
    return await fsp.readFile(file)
  } catch { /* not on disk yet */ }

  if (inFlight.has(gtin)) return inFlight.get(gtin)
  const job = (async () => {
    const buf = await downloadImage(url)
    await fsp.mkdir(IMAGE_DIR, { recursive: true })
    await fsp.writeFile(file, buf)
    return buf
  })().finally(() => inFlight.delete(gtin))
  inFlight.set(gtin, job)
  return job
}

/**
 * Pull a photo in the BACKGROUND, so it is on disk before anything asks for it.
 * Called the moment a barcode resolves and for the top of a search result, which
 * is what turns a 12-second first load into a file read by the time the food
 * reaches the recents list. Failure is silent by design — a missing photo is a
 * letter tile, never an error on screen.
 */
function primeImage(gtin, url) {
  fetchImage(gtin, url).catch(() => {})
}

/* --------------------------------------------------------------- http utils */

const send = (res, status, body, headers = {}) => {
  const payload = typeof body === 'string' ? body : JSON.stringify(body)
  res.writeHead(status, {
    'content-type': typeof body === 'string' ? 'text/plain; charset=utf-8' : 'application/json',
    'cache-control': 'no-store',
    ...headers,
  })
  res.end(payload)
}

/** A body as bytes, for the one route that takes a photo rather than JSON. */
function readRaw(req, limit = 10 * 1024 * 1024) {
  return new Promise((resolve, reject) => {
    let size = 0
    const chunks = []
    req.on('data', c => {
      size += c.length
      if (size > limit) { reject(new Error('That photo is too large.')); req.destroy(); return }
      chunks.push(c)
    })
    req.on('end', () => resolve(Buffer.concat(chunks)))
    req.on('error', reject)
  })
}

/*
 * A JSON body must say it is JSON. A cross-site form can send text/plain or
 * form-encoded bodies without a preflight; it cannot send application/json.
 */
const isJsonType = (req) => /^application\/(?:[\w.+-]+\+)?json\b/i.test(String(req.headers['content-type'] || '').trim())
const httpError = (status, message) => Object.assign(new Error(message), { status })

function readBody(req, limit = 8 * 1024 * 1024) {
  return new Promise((resolve, reject) => {
    let size = 0
    const chunks = []
    req.on('data', c => {
      size += c.length
      if (size > limit) { reject(new Error('body too large')); req.destroy(); return }
      chunks.push(c)
    })
    req.on('end', () => {
      if (chunks.length && !isJsonType(req)) { reject(httpError(415, 'Send JSON with Content-Type: application/json.')); return }
      try {
        resolve(chunks.length ? JSON.parse(Buffer.concat(chunks).toString('utf8')) : {})
      } catch (e) {
        reject(httpError(400, 'invalid JSON'))
      }
    })
    req.on('error', reject)
  })
}

