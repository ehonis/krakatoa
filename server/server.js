const EMPTY = { version: 1, updatedAt: null, entries: {} }

async function readState() {
  try {
    const raw = await fsp.readFile(STATE_FILE, 'utf8')
    const doc = JSON.parse(raw)
    return { ...EMPTY, ...doc, entries: doc.entries || {} }
  } catch (e) {
    if (e.code !== 'ENOENT') console.error('[krakatoa] state unreadable, starting empty:', e.message)
    return { ...EMPTY }
  }
}

/** Write via a temp file and rename, so a crash mid-write cannot truncate the log. */
async function writeState(doc) {
  await fsp.mkdir(DATA_DIR, { recursive: true })
  const tmp = `${STATE_FILE}.tmp`
  await fsp.writeFile(tmp, JSON.stringify(doc, null, 2))
  await fsp.rename(tmp, STATE_FILE)
}

async function backup() {
  try {
    await fsp.mkdir(BACKUP_DIR, { recursive: true })
    const stamp = new Date().toISOString().replace(/[:.]/g, '-')
    await fsp.copyFile(STATE_FILE, path.join(BACKUP_DIR, `state-${stamp}.json`))
    const files = (await fsp.readdir(BACKUP_DIR)).filter(f => f.startsWith('state-')).sort()
    for (const f of files.slice(0, Math.max(0, files.length - MAX_BACKUPS))) {
      await fsp.unlink(path.join(BACKUP_DIR, f)).catch(() => {})
    }
  } catch { /* a backup that fails must never fail the write it was protecting */ }
}

/**
 * Merge incoming entries into what is on disk, per entry, newest updatedAt wins.
 * An entry the server has never seen is taken as-is; one it has seen is taken
 * only if the incoming copy is strictly newer. That makes the PUT idempotent and
 * makes a phone that has been offline for a week safe to sync.
 */
function mergeEntries(mine, theirs) {
  const out = { ...mine }
  for (const [id, entry] of Object.entries(theirs || {})) {
    if (!entry || typeof entry !== 'object') continue
    const have = out[id]
    if (!have) { out[id] = entry; continue }
    const a = String(have.updatedAt || '')
    const b = String(entry.updatedAt || '')
    if (b >= a) out[id] = entry
  }
  return out
}

let writing = Promise.resolve()
/** Serialize writes. Two requests landing together must not both read-modify-write. */
function withState(fn) {
  const next = writing.then(async () => {
    const doc = await readState()
    const result = await fn(doc)
    return result
  })
  writing = next.catch(() => {})
  return next
}

/*
 * The file other agents read. Bushido's coach is given this directory and told to
 * read THIS, not state.json — a pre-digested fortnight is about 3 KB against a
 * log that grows without limit, and Bushido already learned that lesson expensively
 * when its week planner timed out reading a 200 KB log it should have grepped.
 */
async function writeDigest(state) {
  try {
    const body = digest.digest(state, {
      today: digest.isoDate(new Date()),
      days: 14,
      whoop: whoopStore.read(),
    })
    await fsp.writeFile(path.join(DATA_DIR, 'digest.json'), JSON.stringify({
      generatedAt: new Date().toISOString(),
      app: 'krakatoa',
      note: 'Read-only summary for other agents. The store itself is state.json.',
      ...body,
    }, null, 2))
  } catch (e) {
    console.error('[krakatoa] could not write the digest:', e.message)
  }
}

async function commit(doc, incoming) {
  const merged = {
    version: 1,
    updatedAt: new Date().toISOString(),
    entries: mergeEntries(doc.entries, incoming),
  }
  if (fs.existsSync(STATE_FILE)) await backup()
  await writeState(merged)
  // Both best effort and neither awaited into the response: Totem being down, or
  // a digest that will not write, must never fail a food log — exactly as Totem
  // must never fail a training log in Bushido.
  if (eff().digestFile.value) writeDigest(merged).catch(() => {})
  const bridge = totemCfg()
  if (bridge) totem.syncDay(merged, digest, undefined, bridge).catch(() => {})
  return merged
}

