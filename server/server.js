/* The Test buttons in Settings. Each answers { ok, detail } and never throws. */
async function testIntegration(what) {
  const started = Date.now()
  const done = (ok, detail) => ({ what, ok, detail, ms: Date.now() - started })
  try {
    if (what === 'ai') {
      if (!aiReady()) return done(false, AI_NOT_SET_UP)
      const c = aiCfg()
      const out = await new Promise((resolve, reject) => {
        const { execFile } = require('child_process')
        execFile(c.bin, ['--print', '--model', c.askModel, '--output-format', 'json', '--no-session-persistence', '--tools', '', 'Reply with exactly: OK'],
          { timeout: 90000, env: c.env || process.env, maxBuffer: 1024 * 1024 },
          (err, stdout, stderr) => (err ? reject(new Error(String(stderr || err.message).trim().slice(0, 300))) : resolve(stdout)))
      })
      let reply = out
      try { const j = JSON.parse(out); if (j.is_error) return done(false, String(j.result || 'the CLI reported an error').slice(0, 300)); reply = j.result } catch { /* plain text */ }
      return done(true, `${c.askModel} answered: ${String(reply).trim().slice(0, 60)}`)
    }
    if (what === 'usda') {
      const key = usdaKey()
      const r = await fetch(`https://api.nal.usda.gov/fdc/v1/foods/search?query=egg&pageSize=1&api_key=${encodeURIComponent(key)}`, { signal: AbortSignal.timeout(10000) })
      if (!r.ok) return done(false, `USDA answered ${r.status}${key === 'DEMO_KEY' ? ' (using DEMO_KEY)' : ''}`)
      return done(true, key === 'DEMO_KEY' ? 'Works, on the shared DEMO_KEY (about 30 requests an hour).' : 'Key accepted.')
    }
    if (what === 'nutritionix') {
      const out = await nutritionix.search('apple', nixConfig())
      if (!out.configured) return done(false, 'No Nutritionix app ID and key.')
      return done(true, `Answered with ${out.foods.length} results.`)
    }
    if (what === 'totem') {
      if (!totemCfg()) return done(false, 'The Totem bridge is off, or no bridge secret was found.')
      const doc = await whoopStore.refresh()
      return doc.error ? done(false, doc.error) : done(true, `Connected. ${Object.keys(doc.burn || {}).length} days of WHOOP burn.`)
    }
    return done(false, `nothing to test called "${what}"`)
  } catch (e) {
    return done(false, String(e.message || e))
  }
}

