#!/usr/bin/env node
/*
 * Krakatoa — self-hosted food log API + static app server.
 *
 * Zero dependencies, same shape as Bushido's server so the two are one thing to
 * learn. Serves the built React app and a small JSON API backed by a single file
 * on disk. Single-owner sign-in is built in (server/auth.js); KRAKATOA_AUTH=proxy
 * leaves it to an authenticating proxy instead, such as Cloudflare Access.
 *
 *   GET  /login, /setup           the sign-in and first-run pages (server/pages.js)
 *   POST /api/auth/login|setup|logout|password
 *   GET  /api/me                  who is signed in, and which features are configured
 *   GET|PUT /api/settings         Settings, secrets masked. See server/settings.js.
 *   GET  /api/settings/ai/status  is the CLI installed and signed in
 *   POST /api/settings/test       { what: 'ai'|'usda'|'nutritionix'|'totem' }
 *   POST /api/settings/token      a new API token for machine callers (shown once)
 *   GET  /api/health              liveness + paths
 *   GET  /api/state               { version, updatedAt, state }
 *   PUT  /api/state               { state } -> merged with disk, returns merged doc
 *   POST /api/entry               { entry } -> upsert one entry, returns merged doc
 *   GET  /api/lookup?code=        one barcode -> a food (OFF, then USDA)
 *   POST /api/label               a photo of a Nutrition Facts label -> its numbers
 *   POST /api/ask                 a receipt, a plate or words -> a background thread (202)
 *   POST /mcp                     MCP (Streamable HTTP, JSON) — Krakatoa's tools for Totem. See server/mcp.js.
 *   GET  /api/ask/threads         the Ask AI threads, newest first
 *   GET|POST|DELETE /api/ask/threads/<id>   one thread; POST saves his draft, seen, logged, retry
 *   POST /api/food                { food } -> remember a food he built, under its barcode
 *   GET  /api/search?q=           free-text -> foods (the door for unpackaged food)
 *   GET  /api/basics              the generic-food catalog (content/basics.json)
 *   GET  /api/restaurants         chain menus (content/restaurants.json, optional) + learned ones
 *   GET  /api/restaurant?q=       chain menu items (Nutritionix; needs a key)
 *   GET  /api/restaurant/item?id= one menu item in full, with its macros
 *   GET  /api/whoop               cached daily calorie burn (data/whoop.json)
 *   POST /api/whoop/pull          refetch from the bridge now (the button)
 *   GET  /api/image?gtin=&u=      one product photo, proxied and cached to disk
 *   GET  /api/recent              foods worth offering again, most recent first
 *   GET  /api/day?date=           one day resolved: total, target, what filled it
 *   GET  /api/digest?days=        what the AGENTS read. See server/digest.js.
 *   GET  /api/export              full state as a download
 *   POST /api/import              replace state wholesale (from an export file)
 *
 * Writes are last-write-wins per entry id, using each entry's own updatedAt — so
 * two devices can both be offline, both write, and neither loses anything except
 * a genuine same-entry edit. No conflict dialogs, ever.
 */

